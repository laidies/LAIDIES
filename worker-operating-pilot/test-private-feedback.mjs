import assert from 'node:assert/strict';
import { privateFeedbackFetch } from './src/private-feedback.mjs';
import { canonicalSubmissionDigest } from './src/feedback-contract.mjs';
const origin = 'https://private.example';
const env = { PRIVATE_FEEDBACK_ENABLED: 'true', PRIVATE_FEEDBACK_OWNER_TOKEN: 'a'.repeat(64), PRIVATE_FEEDBACK_DB_CAPABILITY: 'b'.repeat(64), PRIVATE_FEEDBACK_ACTOR_SECRET: 'c'.repeat(64), PRIVATE_FEEDBACK_SUPABASE_URL: 'https://database.example', PRIVATE_FEEDBACK_ANON_KEY: 'public-key' };
let calls = 0;
const actors = [];
const input = { submission_type: 'suggestion', body: 'Synthetic integration check' };
const receipt = { contract_version: 'town_hall_feedback_receipt.v1', receipt_id: crypto.randomUUID(), status: 'accepted', accepted_at: '2026-09-05T00:00:00.000Z', input_sha256: await canonicalSubmissionDigest(input) };
const provider = async (url, init) => {
  calls++;
  assert.equal(url.href, 'https://database.example/rest/v1/rpc/private_feedback_bridge_v1');
  assert.equal(init.headers.apikey, 'public-key');
  assert.equal(init.redirect, 'manual');
  const body = JSON.parse(init.body);
  assert.equal(body.p_capability, env.PRIVATE_FEEDBACK_DB_CAPABILITY);
  if (body.p_action === 'intake') actors.push(body.p_payload.actor_hash);
  assert.ok(!init.body.includes(env.PRIVATE_FEEDBACK_OWNER_TOKEN));
  return Response.json(body.p_action === 'list' ? [] : body.p_action === 'intake' ? receipt : { reviewed: true });
};
const req = (action, payload = {}, extra = {}) => new Request(`${origin}/private-feedback/api/${action}`, { method: 'POST', headers: { Origin: origin, Authorization: `Bearer ${env.PRIVATE_FEEDBACK_OWNER_TOKEN}`, 'Content-Type': 'application/json', 'CF-Connecting-IP': '192.0.2.1', 'Idempotency-Key': crypto.randomUUID(), 'X-Turnstile-Token': 'private-owner', ...extra }, body: JSON.stringify(payload) });
for (const token of ['', `Bearer ${'d'.repeat(64)}`, 'Bearer invalid']) assert.equal((await privateFeedbackFetch(req('list', {}, { Authorization: token }), env, provider)).status, 403);
assert.equal(calls, 0);
assert.equal((await privateFeedbackFetch(req('list'), { ...env, PRIVATE_FEEDBACK_ENABLED: 'false' }, provider)).status, 503);
assert.equal((await privateFeedbackFetch(req('list', {}, { Origin: 'https://evil.example' }), env, provider)).status, 403);
assert.equal((await privateFeedbackFetch(req('list', {}, { 'Content-Type': 'text/plain' }), env, provider)).status, 415);
assert.equal((await privateFeedbackFetch(new Request(`${origin}/api/town-hall/feedback`), env, provider)).status, 404);
assert.equal(calls, 0);
assert.deepEqual(await (await privateFeedbackFetch(req('list'), env, provider)).json(), []);
assert.deepEqual(await (await privateFeedbackFetch(req('intake', input), env, provider)).json(), receipt);
assert.equal((await privateFeedbackFetch(req('review', { id: receipt.receipt_id, status: 'triaged' }), env, provider)).status, 200);
assert.equal((await privateFeedbackFetch(req('intake', { ...input, admin_notes: 'forged' }), env, provider)).status, 400);
assert.equal(calls, 3);
await privateFeedbackFetch(req('intake', input, { 'CF-Connecting-IP': '203.0.113.2' }), env, provider);
assert.equal(actors[0], actors[1]);
const failed = await privateFeedbackFetch(req('list'), env, async () => Response.json({ message: 'private secret provider error' }, { status: 500 }));
assert.equal(failed.status, 503);
assert.ok(!(await failed.text()).includes('secret'));
const shell = await privateFeedbackFetch(new Request(`${origin}/private-feedback/`), { PRIVATE_FEEDBACK_ASSETS: { fetch: async () => new Response('<h1>Private inbox</h1>') } });
assert.equal(shell.headers.get('Referrer-Policy'), 'no-referrer');
assert.equal(shell.headers.get('Cache-Control'), 'no-store');
assert.ok(shell.headers.get('Content-Security-Policy').includes("frame-ancestors 'none'"));
console.log('PRIVATE WORKER PASS denied_bad_tokens=3 origin_media_gate=2 public_route_closed=1 private_actions=3 provider_error_redacted=1 shell_policy=1');

const redirect = await privateFeedbackFetch(req('list'), env, async (_url, init) => {
  assert.equal(init.redirect, 'manual');
  return new Response(null, { status: 302, headers: { Location: 'https://untrusted.invalid' } });
});
assert.equal(redirect.status, 503);
console.log('PRIVATE REDIRECT PASS provider_redirect_not_followed_or_returned=1');
