import assert from 'node:assert/strict';
import {createQuizFirstRewardClient} from '../content/site/quiz-first-reward-client.mjs';
const a='aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa',b='bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb';
let owner=a,calls=[],afterCall=()=>{},authCallback;
const award={state:'claimed',episode:'01',score:6,max_score:10,clips:6};
const runtime={controller:{async getSession(){return {user:{id:owner}};}},client:{auth:{onAuthStateChange(fn){authCallback=fn;return {data:{subscription:{unsubscribe(){}}}};}},async rpc(name,args){calls.push({name,args});afterCall();return {data:award,error:null};}}};
const client=createQuizFirstRewardClient(runtime);
const attempt={episode:'01',version:'2026-09-06-v2',attemptId:'11111111-1111-4111-8111-111111111111',answers:{q:0}};
assert.deepEqual(await client.submit(attempt,a),award);
assert.equal(calls[0].args.p_expected_owner,a);
assert.equal('score' in calls[0].args,false);
await client.submit(attempt,a);
assert.deepEqual(calls[0],calls[1],'same retry sends identical request');
assert.throws(()=>client.submit({...attempt,answers:{q:1}},a),/retry-changed/);
owner=b;let before=calls.length;
await assert.rejects(()=>client.read('01',a),/account-changed/);
assert.equal(calls.length,before,'wrong owner never calls RPC');
owner=a;afterCall=()=>{owner=b;};
await assert.rejects(()=>client.read('01',a),/account-changed/);
owner=a;afterCall=()=>authCallback('TOKEN_REFRESHED',{});
await assert.rejects(()=>client.read('01',a),/account-changed/);
afterCall=()=>{};client.dispose();before=calls.length;
await assert.rejects(()=>client.read('01',a),/account-changed/);
assert.equal(calls.length,before);
console.log('QUIZ FIRST REWARD CLIENT: exact retry, wrong-owner, late-owner and invalidation checks passed');
