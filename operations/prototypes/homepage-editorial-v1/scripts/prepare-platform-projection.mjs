import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  entryCurrentContentReceiver,
  receiveProjection,
  sealProjectionDraft
} from "../../../product-stewards/platform-reliability/readiness-projection/v1/readiness-projection-v1.mjs";
import {
  fixtureReadEvidence,
  makeValidDraft,
  makeValidEnvelope
} from "../../../product-stewards/platform-reliability/readiness-projection/v1/fixtures-v1.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const observedNow = new Date("2026-07-26T18:16:00Z");
const staleNow = new Date("2026-07-27T18:15:01Z");
const freshEnvelope = await makeValidEnvelope();
const freshReceipt = receiveProjection(freshEnvelope, {
  now: observedNow,
  expectedPayloadSha256: freshEnvelope.integrity.payloadSha256
});

const conflictDraft = makeValidDraft();
conflictDraft.destinations[0].summary =
  "Conflicting bytes under the same projection identifier.";
const conflictEnvelope = await sealProjectionDraft(conflictDraft, {
  now: observedNow,
  readEvidence: fixtureReadEvidence
});
const conflictReceipt = receiveProjection(conflictEnvelope, {
  now: observedNow,
  previousReceipt: {
    projectionId: freshReceipt.projectionId,
    projectionSha256: freshReceipt.projectionSha256,
    sequence: freshReceipt.sequence
  }
});
const staleReceipt = receiveProjection(freshEnvelope, { now: staleNow });

function scenario(receipt) {
  return {
    receipt,
    currentContent: entryCurrentContentReceiver(receipt)
  };
}

const bundle = {
  contractVersion: "1.0.0",
  evidenceCeiling: "SYNTHETIC_PLATFORM_CONTRACT_FIXTURE_NOT_OWNER_ADMISSION",
  sourceContract:
    "operations/product-stewards/platform-reliability/readiness-projection-contract-v1-2026-07-26.md",
  envelope: freshEnvelope,
  scenarios: {
    fresh: scenario(freshReceipt),
    stale: scenario(staleReceipt),
    conflict: scenario(conflictReceipt)
  }
};

const binding = {
  schemaVersion: freshEnvelope.schemaVersion,
  recordType: freshEnvelope.recordType,
  projectionId: freshEnvelope.payload.projectionId,
  payloadSha256: freshEnvelope.integrity.payloadSha256,
  sequence: freshEnvelope.payload.sequence,
  canonicalDestinations: freshEnvelope.payload.destinations.map((item) => ({
    destinationId: item.destinationId,
    productId: item.productId,
    ownerId: item.ownerId,
    name: item.name,
    route: item.route
  }))
};

const dataPath = resolve(root, "public/data/readiness-current-projection-v1.json");
const bindingPath = resolve(root, "src/generated/platform-projection-binding-v1.js");
mkdirSync(dirname(dataPath), { recursive: true });
mkdirSync(dirname(bindingPath), { recursive: true });
writeFileSync(dataPath, `${JSON.stringify(bundle, null, 2)}\n`);
writeFileSync(
  bindingPath,
  `// Generated by scripts/prepare-platform-projection.mjs. Do not edit.\n` +
    `export const PLATFORM_PROJECTION_BINDING = Object.freeze(${JSON.stringify(binding, null, 2)});\n`
);

console.log(
  `Prepared Platform projection ${binding.projectionId} ${binding.payloadSha256}`
);
