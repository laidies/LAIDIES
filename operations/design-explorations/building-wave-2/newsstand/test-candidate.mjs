#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const dir=path.dirname(fileURLToPath(import.meta.url));
const html=fs.readFileSync(path.join(dir,'index.html'),'utf8'); const css=fs.readFileSync(path.join(dir,'candidate.css'),'utf8'); const js=fs.readFileSync(path.join(dir,'candidate.js'),'utf8');
let n=0; const ok=(v,m)=>{assert.equal(v,true,m);n++};
ok((html.match(/data-edition=/g)||[]).length===4,'four operable paper controls');
for(const word of ['The Breaking','The Daily','The Weekly','The Tribune']) ok(html.includes(word),`${word} identity`);
ok(!html.includes('TODAY')&&!html.includes('WEDNESDAY'),'does not use legacy masthead labels');
ok(html.includes('Put the paper back'),'in-place reader has return');
ok(html.includes('id="radio"')&&html.includes('aria-pressed'),'explicit radio control');
ok(html.includes('Find a back issue.')&&html.includes('id="search-form"'),'back-issue crate search');
ok(js.includes("fixture === 'quiet'")&&js.includes("fixture === 'hold'")&&js.includes("fixture === 'stale'")&&js.includes("fixture === 'retracted'")&&js.includes("fixture === 'malformed'"),'all deterministic failure fixtures');
ok(js.includes('decision(s.edition,s,\'search\')'),'archive filters through access decision');
ok(js.includes('target?.focus'),'put-back focus return');
ok(css.includes('@media(max-width:700px)')&&css.includes('@media(max-width:340px)'),'390 and 320 responsive layouts');
ok(css.includes('prefers-reduced-motion'),'reduced-motion declaration');
ok(html.includes('newsstand-reader-contract.js')&&html.includes('newsstand-stories.js'),'reads canonical inputs');
ok((html.match(/data-edition=[^>]+disabled/g)||[]).length===4,'no-JS starts all paper objects disabled');
ok(html.includes('data-js-enable disabled')&&html.includes('The dated reader is unavailable without JavaScript.'),'explicit no-JS boundary');
ok(html.includes('id="room-fallback"')&&js.includes("roomImage.addEventListener('error'"),'visible room art fallback');
ok(js.includes("if (ds.state === 'load-failure') return 'desk unavailable'")&&js.includes("if (ds.state === 'hold') return 'desk hold'"),'global desk gate owns paper labels');
ok(js.includes('focusReaderTitle()')&&js.includes("showNotice('Story unavailable.'"),'direct failure focus path');
console.log(`NEWSSTAND WAVE 2 CANDIDATE PASS checks=${n}`);
